#!/usr/bin/env node
/**
 * Scans presentation folders and builds manifest.json
 * from folder structure + HTML <title> tags.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const MANIFEST_PATH = path.join(ROOT, 'manifest.json');
const MANIFEST_JS_PATH = path.join(ROOT, 'manifest.js');
const SKIP_DIRS = new Set(['scripts', 'node_modules', '.git']);
const SKIP_FILES = new Set(['index.html']);

function extractTitle(html) {
  const match = html.match(/<title[^>]*>([\s\S]*?)<\/title>/i);
  return match ? match[1].trim() : null;
}

function readFolderMeta(folderPath, folderName) {
  const metaPath = path.join(folderPath, 'folder.json');
  const defaults = { name: folderName };
  if (!fs.existsSync(metaPath)) return defaults;

  try {
    const meta = JSON.parse(fs.readFileSync(metaPath, 'utf8'));
    return {
      name: meta.name || folderName,
      copyright: meta.copyright || null,
    };
  } catch {
    return defaults;
  }
}

function scanPresentations() {
  const categories = [];

  const entries = fs.readdirSync(ROOT, { withFileTypes: true });
  for (const entry of entries) {
    if (!entry.isDirectory() || SKIP_DIRS.has(entry.name)) continue;

    const folderPath = path.join(ROOT, entry.name);
    const presentations = [];

    const files = fs
      .readdirSync(folderPath)
      .filter((f) => f.endsWith('.html'))
      .sort((a, b) => a.localeCompare(b, 'zh-Hant'));

    for (const file of files) {
      const filePath = path.join(folderPath, file);
      const html = fs.readFileSync(filePath, 'utf8');
      const title = extractTitle(html) || file.replace(/\.html$/, '');

      presentations.push({
        id: file.replace(/\.html$/, ''),
        title,
        path: `${entry.name}/${file}`,
      });
    }

    if (presentations.length > 0) {
      const meta = readFolderMeta(folderPath, entry.name);
      const category = {
        id: entry.name,
        name: meta.name,
        presentations,
      };
      if (meta.copyright) category.copyright = meta.copyright;
      categories.push(category);
    }
  }

  categories.sort((a, b) => a.name.localeCompare(b.name, 'zh-Hant'));
  return { categories, generatedAt: new Date().toISOString() };
}

const manifest = scanPresentations();
const json = JSON.stringify(manifest, null, 2) + '\n';
fs.writeFileSync(MANIFEST_PATH, json);
fs.writeFileSync(
  MANIFEST_JS_PATH,
  `// Auto-generated by scripts/build-manifest.js — do not edit\nwindow.PRESENTATION_MANIFEST = ${JSON.stringify(manifest)};\n`
);
console.log(`Wrote ${MANIFEST_PATH} (${manifest.categories.length} categories)`);
console.log(`Wrote ${MANIFEST_JS_PATH}`);
